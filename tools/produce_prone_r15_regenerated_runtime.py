#!/usr/bin/env python3
"""Produce/verify private dense runtime for a strictly proven regenerated r15.

Only a serialized native owner or the isolated admitted Windows job may execute
produce. This script never renders, uploads, changes a source BLEND, mutates an
original verifier pin, or assigns approved-source identity to generated bytes.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import subprocess
import sys
import time

import prone_r15_regenerated_contract as contract
from run_prone_r15_source_proof import exclusive_lock

ORIGINAL_RIGID_SHA = "2ff8f004c487c9a3ef634f157838897a4e6ae9773b72f55f372c16f2f5e44095"
CANONICAL_SHA = "d02d04d4adb429b6493bf3347b302dc007bb7b99f4761da3c2b314e6d313c6ab"
RUNTIME_FILES = ("asset.vra", "asset.vrs", "asset.vrm", "asset.prone-camera.json", "asset.prone-pair.json", "manifest.json")


def native_command(blender, script, arguments, source=None):
    command = [blender, "--background", "--factory-startup", "--disable-autoexec", "--threads", "1"]
    if source is not None:
        command.append(source)
    return [*command, "--python-exit-code", "1", "--python", script, "--", *arguments]


def conversion_arguments(args, fbx, camera, skeleton):
    result = ["--fbx", fbx, "--fbx-sha256", contract.sha(fbx), "--source-sha256", contract.sha(args.source),
        "--material-source", args.source, "--skeleton-vra", skeleton, "--output", args.output,
        "--native-start", "0", "--native-end", "68", "--subdivisions", "64", "--fps", "60",
        "--take", contract.ACTION, "--imported-frame-offset", "1", "--name", contract.ACTION,
        "--pair-sidecar", camera, "--pair-sidecar-sha256", contract.sha(camera), "--pair-candidate-source", args.source,
        "--pair-rig-action-fingerprint", contract.delta.RIG_FINGERPRINT,
        "--pair-camera-action-fingerprint", contract.delta.CAMERA_FINGERPRINT, "--pair-candidate-frame-offset", "1"]
    for actor in contract.ACTORS:
        result += ["--actor", actor]
    return result


def dense_directory(args):
    return getattr(args, "existing_dense", None) or args.work / "dense"


def write_grid(path):
    # Bytes avoid Windows text newline conversion of the independently pinned grid.
    with path.open("xb") as stream:
        stream.write((json.dumps(contract.grid()) + "\n").encode("utf-8"))
    contract.require(contract.sha(path) == contract.GRID_SHA, "grid bytes differ")


def validate_existing_dense(args, proof):
    """Adopt only a complete actual export/fresh-import proof, without re-export."""
    dense = dense_directory(args)
    receipt = contract.read(dense / "export-receipt.json")
    parity = contract.read(dense / "fresh-import-parity.json")
    oracle = args.reference_oracle or dense
    provenance = {"generated_source_sha256": contract.sha(args.source),
        "source_fbx_sha256": contract.sha(dense / (contract.ACTION + ".fbx")),
        "source_equivalence_sha256": contract.sha(args.source_equivalence),
        "source_equivalence_descriptor": proof}
    contract.validate_dense_evidence(receipt, parity, provenance)
    required_recipes = ("export_prone_r15_regenerated_dense.py", "prone_r15_regenerated_contract.py")
    contract.require(receipt["recipes"] == {name: contract.sha(args.root / "tools" / name) for name in required_recipes},
                     "adopted dense recipe differs")
    contract.require(receipt["source_samples_sha256"] == contract.sha(oracle / "source-samples.json") and
                     receipt["oracle_source_sha256"] == (contract.delta.APPROVED_SHA if args.reference_oracle else provenance["generated_source_sha256"]),
                     "adopted dense oracle differs")
    contract.require(receipt["evidence_sha256"] == {name: contract.sha(dense / name) for name in
                     ("paired-camera-contract.json", "fbx-take-contract.json")}, "adopted dense evidence differs")
    take = contract.read(dense / "fbx-take-contract.json")
    contract.require(take["matches"] is True and take["animation_stacks"] == [contract.ACTION] and
                     take["expected_single_stack"] == contract.ACTION, "adopted dense take differs")
    return dense


def check_paths(args):
    for name in ("root", "source", "source_equivalence", "blender", "work", "output", "runtime_sampler", "camera_sampler"):
        path = getattr(args, name).absolute()
        contract.require(not any(p.is_symlink() or (hasattr(p, "is_junction") and p.is_junction()) for p in (path, *path.parents)),
                         "linked producer path forbidden")
        setattr(args, name, path.resolve())
    contract.require(not args.work.is_relative_to(args.root) and not args.root.is_relative_to(args.work), "private work must be outside checkout")
    contract.require(not args.output.is_relative_to(args.root) and not args.root.is_relative_to(args.output), "private runtime must be outside checkout")
    contract.require(not args.output.is_relative_to(args.work) and not args.work.is_relative_to(args.output), "runtime and work must be disjoint")
    contract.require(args.source.suffix.lower() == ".blend" and args.source.is_file(), "existing generated BLEND required")
    for path in (args.blender, args.runtime_sampler, args.camera_sampler):
        contract.require(path.is_file(), "native tool missing")
    contract.require((args.reference_oracle is None) == (args.reference_rigid is None), "reference oracle and rigid oracle must be supplied together")
    if args.reference_oracle is not None:
        args.reference_oracle = args.reference_oracle.resolve()
        args.reference_rigid = args.reference_rigid.resolve()
        contract.require(contract.sha(args.reference_oracle / "source-samples.json") == contract.ORIGINAL_ORACLE_SHA,
                         "immutable approved private source oracle differs")
        contract.require(contract.sha(args.reference_rigid) == ORIGINAL_RIGID_SHA, "immutable approved private rigid oracle differs")
    if getattr(args, "existing_dense", None) is not None:
        dense = args.existing_dense.absolute()
        contract.require(not any(p.is_symlink() or (hasattr(p, "is_junction") and p.is_junction()) for p in (dense, *dense.parents)),
                         "linked existing dense output forbidden")
        args.existing_dense = dense.resolve()
        contract.require(dense.is_dir() and not dense.is_relative_to(args.root) and not args.root.is_relative_to(dense),
                         "existing dense output must be private and outside checkout")
        for other in (args.work, args.output):
            contract.require(not dense.is_relative_to(other) and not other.is_relative_to(dense), "existing dense output overlaps new output")
    skeleton = (args.skeleton_vra or args.root / "assets/locomotion/asset.vra").resolve()
    contract.require(contract.sha(skeleton) == CANONICAL_SHA, "canonical runtime hierarchy source differs")
    return skeleton


def run_phase(args, label, command, native=False):
    log = args.work / (label + ".log")
    receipt = args.work / (label + ".process.json")
    contract.require(not log.exists() and not receipt.exists(), "fresh stage paths required")
    started = time.monotonic()
    result = {"stage": label, "completed": False, "native_blender": native}
    try:
        with log.open("xb") as stream:
            def invoke():
                return subprocess.run(list(map(str, command)), cwd=args.root, stdout=stream,
                    stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL, timeout=args.timeout_seconds, check=False)
            if native:
                lock = args.native_lock or args.work.parent / "native.lock"
                with exclusive_lock(lock):
                    process = invoke()
            else:
                process = invoke()
        result["exit_code"] = process.returncode
        contract.require(process.returncode == 0, label + " failed; detailed output remains private")
        result["completed"] = True
    finally:
        result.update(seconds=time.monotonic() - started, private_log_sha256=contract.sha(log))
        contract.write(receipt, result)
    print("PRONE_REGENERATED_STAGE", label, "passed", flush=True)


def verifier_command(args, skeleton, oracle, rigid, provenance, report):
    command = [sys.executable, args.root / "tools/verify_prone_r15_runtime.py", args.output / "asset.vra", oracle,
        "--sampler", args.runtime_sampler, "--camera-sampler", args.camera_sampler, "--skeleton-vra", skeleton,
        "--rigid-witness", rigid, "--rigid-witness-sha256", contract.sha(rigid), "--report", report,
        "--regenerated-provenance", provenance, "--regenerated-provenance-sha256", contract.sha(provenance),
        "--generated-source", args.source, "--source-equivalence", args.source_equivalence,
        "--source-equivalence-sha256", contract.sha(args.source_equivalence), "--export-witnesses", dense_directory(args)]
    return command


def validate_cpu_report(path, args, provenance):
    report = contract.read(path)
    for key in ("passed", "complete", "measured_checks_passed", "rigid_geometry_measured"):
        contract.require(report.get(key) is True, "actual Rust CPU parity incomplete: " + key)
    contract.require(report["samples"] == len(report["records"]) == 1944 and report["visibility_failures"] == 0,
                     "actual Rust CPU coverage differs")
    contract.require(report["position_limit_m"] == report["matrix_element_limit"] == 1e-4,
                     "runtime parity thresholds changed")
    contract.require(report["sampler_sha256"] == contract.sha(args.runtime_sampler) and
                     report["camera_sampler_sha256"] == contract.sha(args.camera_sampler) and
                     report["verifier_sha256"] == contract.sha(args.root / "tools/verify_prone_r15_runtime.py"),
                     "actual CPU probe/code identity differs")
    contract.require(report["regenerated_source_provenance"] == provenance, "CPU report provenance differs")
    for frame, row in zip(contract.grid(), report["records"]):
        contract.require(row["source_frame"] == frame and row["requested_time_seconds"] == (frame - 1)/60
                         and row["passed"] is True and row["visibility_matches"] is True, "CPU sample/clock failed")
    return report


def produce(args):
    skeleton = check_paths(args)
    proof_sha = contract.sha(args.source_equivalence)
    proof = contract.descriptor(args.source_equivalence, proof_sha, args.source)
    contract.require(not args.work.exists() and not args.output.exists(), "fresh producer work/runtime required")
    args.work.mkdir(parents=True, mode=0o700)
    code = contract.code_hashes()
    source_sha = contract.sha(args.source)
    grid_path = args.work / "probe-times.json"
    # The original independently approved grid encoding is retained verbatim.
    write_grid(grid_path)
    dense = dense_directory(args)
    dense_args = ["--output-dir", dense, "--source", args.source, "--source-equivalence", args.source_equivalence,
                  "--source-equivalence-sha256", proof_sha]
    if args.reference_oracle is not None:
        dense_args += ["--reference-oracle", args.reference_oracle]
    helper = args.root / "tools/export_prone_r15_regenerated_dense.py"
    if getattr(args, "existing_dense", None) is None:
        run_phase(args, "dense-export", native_command(args.blender, helper, ["export", *dense_args], source=args.source), native=True)
        run_phase(args, "fresh-fbx-import", native_command(args.blender, helper, ["verify", *dense_args]), native=True)
    validate_existing_dense(args, proof)
    camera = args.work / "asset.prone-camera.json"
    run_phase(args, "camera", native_command(args.blender, args.root / "tools/sample_prone_r15_camera.py",
        ["--output", camera, "--source-equivalence", args.source_equivalence, "--source-equivalence-sha256", proof_sha],
        source=args.source), native=True)
    oracle = args.reference_oracle or dense
    rigid = args.reference_rigid or args.work / "rigid-geometry.json"
    if args.reference_rigid is None:
        run_phase(args, "rigid-oracle", native_command(args.blender, args.root / "tools/sample_prone_r15_regenerated_rigid.py",
            ["--grid", grid_path, "--output", rigid, "--source-equivalence", args.source_equivalence,
             "--source-equivalence-sha256", proof_sha], source=args.source), native=True)
    fbx = dense / (contract.ACTION + ".fbx")
    run_phase(args, "paired-conversion", native_command(args.blender, args.root / "tools/import_fbx_viewmodel.py",
        conversion_arguments(args, fbx, camera, skeleton)), native=True)
    provenance = {"schema": "rust-duty-prone-r15-regenerated-runtime-provenance/v1", "generated_source_sha256": source_sha,
        "approved_source_sha256": contract.delta.APPROVED_SHA, "source_equivalence_sha256": proof_sha,
        "source_equivalence_descriptor": proof, "source_witness_sha256": contract.sha(oracle / "source-samples.json"),
        "source_witness_source_sha256": contract.delta.APPROVED_SHA if args.reference_oracle else source_sha,
        "source_fbx_sha256": contract.sha(fbx), "camera_sidecar_sha256": contract.sha(camera),
        "rigid_witness_sha256": contract.sha(rigid),
        "export_evidence_sha256": {name: contract.sha(dense / name) for name in sorted(contract.EVIDENCE_FILES)}, "producer_sha256": code}
    provenance_path = args.work / "runtime-provenance.json"
    contract.write(provenance_path, provenance)
    contract.load_runtime_provenance(provenance_path, contract.sha(provenance_path), args.source, args.source_equivalence, proof_sha)
    contract.validate_dense_evidence(contract.read(dense / "export-receipt.json"), contract.read(dense / "fresh-import-parity.json"), provenance)
    cpu_report = args.work / "cpu-parity-produced.json"
    run_phase(args, "actual-rust-cpu-parity", verifier_command(args, skeleton, oracle, rigid, provenance_path, cpu_report))
    validate_cpu_report(cpu_report, args, provenance)
    contract.require(contract.code_hashes() == code and contract.sha(args.source) == source_sha, "producer/source changed")
    contract.write(args.work / "production.json", {"schema": "rust-duty-prone-r15-regenerated-production/v1", "passed": True,
        "source_sha256": source_sha, "source_equivalence_sha256": proof_sha, "producer_sha256": code,
        "runtime_provenance_sha256": contract.sha(provenance_path), "cpu_parity_sha256": contract.sha(cpu_report),
        "runtime_files_sha256": {name: contract.sha(args.output / name) for name in RUNTIME_FILES},
        "oracle_source_sha256": provenance["source_witness_source_sha256"], "dense_directory": str(dense), "rendered": False})


def verify(args):
    skeleton = check_paths(args)
    production = contract.read(args.work / "production.json")
    contract.require(production["schema"] == "rust-duty-prone-r15-regenerated-production/v1" and production["passed"] is True
                     and production["rendered"] is False, "producer did not finish")
    contract.require(production["source_sha256"] == contract.sha(args.source) and
                     production["source_equivalence_sha256"] == contract.sha(args.source_equivalence) and
                     production["producer_sha256"] == contract.code_hashes(), "producer/proof/source changed")
    contract.require(production["runtime_files_sha256"] == {name: contract.sha(args.output / name) for name in RUNTIME_FILES},
                     "runtime output changed")
    path = args.work / "runtime-provenance.json"
    provenance = contract.load_runtime_provenance(path, production["runtime_provenance_sha256"], args.source,
        args.source_equivalence, production["source_equivalence_sha256"])
    contract.require(contract.sha(args.work / "cpu-parity-produced.json") == production["cpu_parity_sha256"], "CPU report changed")
    validate_cpu_report(args.work / "cpu-parity-produced.json", args, provenance)
    contract.require(production["dense_directory"] == str(dense_directory(args)), "adopted dense directory changed")
    validate_existing_dense(args, provenance["source_equivalence_descriptor"])
    oracle = args.reference_oracle or dense_directory(args)
    rigid = args.reference_rigid or args.work / "rigid-geometry.json"
    # A second independent invocation reopens every actual runtime/oracle input;
    # numerical parity is remeasured, not accepted from the producer's flag.
    report = args.work / "cpu-parity-verified.json"
    run_phase(args, "verify-actual-rust-cpu-parity", verifier_command(args, skeleton, oracle, rigid, path, report))
    validate_cpu_report(report, args, provenance)
    contract.write(args.work / "verified.json", {"schema": "rust-duty-prone-r15-regenerated-production-verification/v1",
        "passed": True, "production_sha256": contract.sha(args.work / "production.json"), "cpu_parity_sha256": contract.sha(report),
        "runtime_provenance_sha256": contract.sha(path), "generated_source_sha256": contract.sha(args.source)})


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ("root", "source", "source-equivalence", "blender", "work", "output", "runtime-sampler", "camera-sampler"):
        parser.add_argument("--" + name, type=Path, required=True)
    for name in ("reference-oracle", "reference-rigid", "skeleton-vra", "native-lock", "existing-dense"):
        parser.add_argument("--" + name, type=Path)
    parser.add_argument("--timeout-seconds", type=int, default=7200)
    parser.add_argument("mode", choices=("produce", "verify"))
    args = parser.parse_args(argv)
    contract.require(30 <= args.timeout_seconds <= 7200, "bounded producer timeout required")
    try:
        (produce if args.mode == "produce" else verify)(args)
    except Exception as error:
        print("Regenerated runtime failed: " + str(error)[:1000], file=sys.stderr)
        return 1
    print("PRONE_REGENERATED_RUNTIME", args.mode, "passed", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
